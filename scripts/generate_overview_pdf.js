import PDFDocument from 'pdfkit';
import fs from 'fs';

const doc = new PDFDocument({ margin: 50 });
const outputStream = fs.createWriteStream('EliteClub_Project_Overview.pdf');

doc.pipe(outputStream);

// Styles
const gold = '#D4AF37';
const champagne = '#F7E7CE';
const dark = '#0A0A0A';

// Header
doc.rect(0, 0, 612, 150).fill(dark);
doc.fillColor(gold).fontSize(40).font('Helvetica-Bold').text('ELITECLUB', 50, 50);
doc.fillColor(champagne).fontSize(14).font('Helvetica').text('PROJECT IMPLEMENTATION OVERVIEW', 50, 100);

doc.moveDown(4);

// Content Section
const section = (title, items) => {
  doc.fillColor(gold).fontSize(18).font('Helvetica-Bold').text(title.toUpperCase());
  doc.rect(doc.x, doc.y + 2, 50, 2).fill(gold);
  doc.moveDown(1);
  
  items.forEach(item => {
    doc.fillColor('#333333').fontSize(12).font('Helvetica-Bold').text('• ' + item.title + ': ', { continued: true });
    doc.font('Helvetica').text(item.desc);
    doc.moveDown(0.5);
  });
  doc.moveDown(1.5);
};

